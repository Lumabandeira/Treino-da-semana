document.addEventListener('DOMContentLoaded', () => {
    const tabs = document.querySelectorAll('.tab-btn');
    const content = document.getElementById('workout-content');

    function renderWorkout(day) {
        const data = workoutData[day];
        if (!data) return;

        let warmupHtml = data.warmup.map(item => `
            <li class="warmup-item">
                <i class="fa-solid fa-fire-flame-curved"></i>
                <span>${item}</span>
            </li>
        `).join('');

        let exercisesHtml = data.exercises.map(ex => `
            <div class="exercise-item">
                <div class="exercise-header">
                    <span class="exercise-name">${ex.name}</span>
                    <a href="${ex.video}" target="_blank" class="video-btn">
                        <i class="fa-brands fa-youtube"></i> Ver Vídeo
                    </a>
                </div>
                <div class="exercise-stats">
                    <div class="stat">
                        <span class="stat-label">Séries</span>
                        <span class="stat-value">${ex.series}</span>
                    </div>
                    <div class="stat">
                        <span class="stat-label">Repetições</span>
                        <span class="stat-value">${ex.reps}</span>
                    </div>
                    <div class="stat">
                        <span class="stat-label">Descanso</span>
                        <span class="stat-value">${ex.rest}</span>
                    </div>
                </div>
            </div>
        `).join('');

        content.innerHTML = `
            <div class="workout-card">
                <div class="section-title">
                    <i class="fa-solid fa-calendar-day"></i>
                    <h2>${data.title}</h2>
                </div>
                
                <h3 style="margin-bottom: 1rem; color: var(--primary);">Aquecimento</h3>
                <ul class="warmup-list">
                    ${warmupHtml}
                </ul>

                <h3 style="margin-bottom: 1rem; color: var(--primary);">Treino Principal</h3>
                <div class="exercise-list">
                    ${exercisesHtml}
                </div>

                <div style="margin-top: 2rem; padding-top: 1rem; border-top: 1px solid rgba(255,255,255,0.1); text-align: right; color: var(--text-muted); font-size: 0.9rem;">
                    <i class="fa-regular fa-clock"></i> Tempo estimado: ${data.time}
                </div>
            </div>
        `;
        
        // Add animation class to new content
        const card = content.querySelector('.workout-card');
        card.style.animation = 'none';
        card.offsetHeight; /* trigger reflow */
        card.style.animation = 'fadeIn 0.5s ease-out';
    }

    tabs.forEach(tab => {
        tab.addEventListener('click', () => {
            // Remove active class from all tabs
            tabs.forEach(t => t.classList.remove('active'));
            // Add active class to clicked tab
            tab.classList.add('active');
            
            // Render content
            const day = tab.getAttribute('data-day');
            renderWorkout(day);
        });
    });

    // Initial render
    renderWorkout('segunda');
});
